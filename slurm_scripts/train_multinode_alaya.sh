#!/usr/bin/env bash
set -euo pipefail

PROJECT_ROOT=${PROJECT_ROOT:-"$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"}
cd "$PROJECT_ROOT"

export RUN_ENTRY=${RUN_ENTRY:-scripts/train.py}
export CONFIG=${CONFIG:-debug}
export EXP_NAME=${EXP_NAME:-"${CONFIG}_alaya"}
export EXTRA_ARGS=${EXTRA_ARGS:-}
export OPENPI_SHOW_TQDM=${OPENPI_SHOW_TQDM:-0}

LOCAL_GPU_COUNT=$(nvidia-smi -L | wc -l)
export JAX_PROCESS_COUNT=${JAX_PROCESS_COUNT:-${PET_NNODES:-${NNODES:-${WORLD_SIZE:-1}}}}
export JAX_PROCESS_INDEX=${JAX_PROCESS_INDEX:-${PET_NODE_RANK:-${NODE_RANK:-${GROUP_RANK:-${RANK:-0}}}}}
export JAX_LOCAL_PROCESS_INDEX=${JAX_LOCAL_PROCESS_INDEX:-0}
export JAX_LOCAL_DEVICE_IDS=${JAX_LOCAL_DEVICE_IDS:-$(seq -s, 0 $((LOCAL_GPU_COUNT - 1)))}
export JAX_COORDINATOR_ADDR=${JAX_COORDINATOR_ADDR:-${MASTER_ADDR:-${PET_MASTER_ADDR:-localhost}}}
export JAX_COORDINATOR_PORT=${JAX_COORDINATOR_PORT:-${MASTER_PORT:-${PET_MASTER_PORT:-29500}}}

unset XLA_CLIENT_MEM_FRACTION XLA_PYTHON_CLIENT_MEM_FRACTION
export XLA_PYTHON_CLIENT_PREALLOCATE=false
export XLA_PYTHON_CLIENT_ALLOCATOR=platform
export TF_CPP_MIN_LOG_LEVEL=${TF_CPP_MIN_LOG_LEVEL:-2}
export NCCL_DEBUG=${NCCL_DEBUG:-INFO}
export NCCL_IB_DISABLE=${NCCL_IB_DISABLE:-0}
export NCCL_NET_GDR_LEVEL=${NCCL_NET_GDR_LEVEL:-PHB}
export NCCL_CROSS_NIC=${NCCL_CROSS_NIC:-1}

if [ "$JAX_PROCESS_INDEX" = 0 ]; then
    mkdir -p slurm_logs
    LOG_TIME=${LOG_TIME:-$(date +%Y%m%d%H%M)}
    LOG_CONFIG=${CONFIG//\//_}
    LOG_CONFIG=${LOG_CONFIG// /_}
    LOG_STEM=${LOG_STEM:-"${LOG_CONFIG}_${LOG_TIME}"}
    exec > "slurm_logs/${LOG_STEM}.out" 2> "slurm_logs/${LOG_STEM}.err"
else
    exec > /dev/null 2>&1
fi

echo "Job started at $(date)"
echo "PROJECT_ROOT=$PROJECT_ROOT"
echo "HOSTNAME=$(hostname)"
echo "JAX_COORDINATOR_ADDR=$JAX_COORDINATOR_ADDR"
echo "JAX_COORDINATOR_PORT=$JAX_COORDINATOR_PORT"
echo "NNODES=$JAX_PROCESS_COUNT"
echo "NODE_RANK=$JAX_PROCESS_INDEX"
echo "LOCAL_GPU_COUNT=$LOCAL_GPU_COUNT"
echo "GLOBAL_DEVICE_COUNT=$((JAX_PROCESS_COUNT * LOCAL_GPU_COUNT))"
echo "JAX_LOCAL_DEVICE_IDS=$JAX_LOCAL_DEVICE_IDS"
echo "CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-}"
echo "RUN_ENTRY=$RUN_ENTRY"
echo "CONFIG=$CONFIG"
echo "EXP_NAME=$EXP_NAME"
echo "EXTRA_ARGS=$EXTRA_ARGS"
echo "XLA_PYTHON_CLIENT_ALLOCATOR=$XLA_PYTHON_CLIENT_ALLOCATOR"
echo "XLA_PYTHON_CLIENT_PREALLOCATE=$XLA_PYTHON_CLIENT_PREALLOCATE"
echo "NCCL_DEBUG=$NCCL_DEBUG"
echo "NCCL_IB_DISABLE=$NCCL_IB_DISABLE"
echo "NCCL_NET_GDR_LEVEL=$NCCL_NET_GDR_LEVEL"
echo "NCCL_CROSS_NIC=$NCCL_CROSS_NIC"
nvidia-smi -L

read -r -a EXTRA_ARGV <<< "$EXTRA_ARGS"
uv run --no-sync "$RUN_ENTRY" "$CONFIG" --exp-name="$EXP_NAME" "${EXTRA_ARGV[@]}"
